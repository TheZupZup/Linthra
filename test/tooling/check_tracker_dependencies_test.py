class FailsClosedTest(unittest.TestCase):
    """A check that passes because its input vanished is worse than no check:
    it reports 'none' about a file nobody read."""

    def test_a_missing_source_file_is_an_error_not_a_pass(self) -> None:
        with tree() as root, policy_file(MINIMAL_POLICY) as policy:
            (root / "pubspec.lock").unlink()
            code, output = run(root, policy)
        self.assertEqual(code, 2, output)
        self.assertIn("pubspec.lock", output)

    def test_a_glob_that_matches_nothing_is_an_error(self) -> None:
        with tree() as root, policy_file(MINIMAL_POLICY) as policy:
            (root / "native" / "linthra_core" / "Cargo.lock").unlink()
            code, output = run(root, policy)
        self.assertEqual(code, 2, output)
        self.assertIn("Cargo.lock", output)

    def test_a_lockfile_entry_without_a_kind_is_an_error(self) -> None:
        lock = "packages:\n  audio_service:\n    source: hosted\n    version: \"1\"\n"
        with tree(lock=lock) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 2, output)
        self.assertIn("dependency", output)

    def test_an_empty_lockfile_is_an_error(self) -> None:
        with tree(lock="packages:\n") as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 2, output)

    def test_a_cmake_file_with_no_plugin_list_is_an_error(self) -> None:
        with tree(cmake="# nothing here\n") as root:
            with policy_file(MINIMAL_POLICY) as policy:
                code, output = run(root, policy)
        self.assertEqual(code, 2, output)

    def test_an_unreadable_policy_is_an_error_not_a_pass(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "tracker_policy.json"
            path.write_text("{ not json", encoding="utf-8")
            with tree() as root:
                code, output = run(root, path)
        self.assertEqual(code, 2, output)
        self.assertIn("not valid JSON", output)


