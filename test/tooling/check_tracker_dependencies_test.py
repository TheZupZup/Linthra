class RealRepositoryTest(unittest.TestCase):
    def test_linthras_own_dependency_graph_passes(self) -> None:
        code, output = run(ROOT, POLICY_PATH)
        self.assertEqual(code, 0, output)
        self.assertIn("Advertising SDKs: none", output)
        self.assertIn("Analytics SDKs: none", output)
        self.assertIn("Automatic third-party crash reporting: none", output)

    def test_it_reads_every_source_it_claims_to(self) -> None:
        code, output = run(ROOT, POLICY_PATH)
        self.assertEqual(code, 0, output)
        for source in (
            "pubspec.lock",
            "flatpak/generated/sources/pubspec.json",
            "linux/flutter/generated_plugins.cmake",
            "android/app/build.gradle",
            "android/settings.gradle",
            "native/linthra_core/Cargo.lock",
        ):
            self.assertIn(source, output)

    def test_it_does_not_claim_to_prove_more_than_it_does(self) -> None:
        _, output = run(ROOT, POLICY_PATH)
        self.assertIn("does not prove", output)
        self.assertIn("docs/tracker-dependency-audit.md", output)

    def test_the_report_is_reproducible(self) -> None:
        first = run(ROOT, POLICY_PATH)
        second = run(ROOT, POLICY_PATH)
        self.assertEqual(first, second)

    def test_the_json_report_is_reproducible_and_says_it_passed(self) -> None:
        code, output = run(ROOT, POLICY_PATH, "--json")
        self.assertEqual(code, 0, output)
        report = json.loads(output)
        self.assertTrue(report["ok"])
        self.assertEqual(report["findings"], [])
        self.assertEqual(
            report["categories"], {key: 0 for key in report["categories"]}
        )
        self.assertEqual(output, run(ROOT, POLICY_PATH, "--json")[1])


