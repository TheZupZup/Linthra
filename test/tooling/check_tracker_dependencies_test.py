class PolicyDataTest(unittest.TestCase):
    """The reviewed data has to parse the same way every time, or it is not
    reviewed data — it is a file somebody hopes says what they meant."""

    def test_the_real_policy_loads(self) -> None:
        policy = checker.load_policy(POLICY_PATH)
        self.assertGreater(len(policy.entries), 40)
        self.assertEqual(policy.version, 1)

    def test_loading_is_deterministic(self) -> None:
        first = checker.load_policy(POLICY_PATH)
        second = checker.load_policy(POLICY_PATH)
        self.assertEqual(first.entries, second.entries)
        self.assertEqual(
            [entry.identifier for entry in first.entries],
            [entry.identifier for entry in second.entries],
        )

    def test_every_real_entry_is_explained_and_categorised(self) -> None:
        policy = checker.load_policy(POLICY_PATH)
        for entry in policy.entries:
            with self.subTest(entry=entry.identifier):
                self.assertIn(entry.category, policy.categories)
                self.assertGreater(len(entry.rationale), 20)
                self.assertTrue(entry.vendor.strip())

    def test_the_real_policy_names_the_systems_the_issue_named(self) -> None:
        policy = checker.load_policy(POLICY_PATH)
        named = {entry.identifier for entry in policy.entries}
        for identifier in (
            "firebase_analytics",
            "firebase_crashlytics",
            "sentry_flutter",
            "mixpanel_flutter",
            "amplitude_flutter",
            "adjust_sdk",
            "appsflyer_sdk",
            "facebook_app_events",
            "com.google.android.gms:play-services-analytics",
        ):
            self.assertIn(identifier, named)

    def test_the_real_policy_covers_every_category(self) -> None:
        policy = checker.load_policy(POLICY_PATH)
        used = {entry.category for entry in policy.entries}
        self.assertEqual(used, set(policy.categories))

    def test_an_unsorted_denylist_is_rejected(self) -> None:
        policy = minimal_policy()
        policy["denylist"].reverse()
        with policy_file(policy) as path:
            with self.assertRaisesRegex(checker.PolicyError, "sorted"):
                checker.load_policy(path)

    def test_a_duplicate_entry_is_rejected(self) -> None:
        policy = minimal_policy()
        policy["denylist"].insert(3, json.loads(json.dumps(policy["denylist"][2])))
        with policy_file(policy) as path:
            with self.assertRaisesRegex(checker.PolicyError, "duplicate"):
                checker.load_policy(path)

    def test_a_blank_rationale_is_rejected(self) -> None:
        policy = minimal_policy()
        policy["denylist"][0]["rationale"] = "   "
        with policy_file(policy) as path:
            with self.assertRaisesRegex(checker.PolicyError, "rationale"):
                checker.load_policy(path)

    def test_an_unknown_key_is_rejected(self) -> None:
        policy = minimal_policy()
        policy["denylist"][0]["severity"] = "high"
        with policy_file(policy) as path:
            with self.assertRaisesRegex(checker.PolicyError, "unknown key"):
                checker.load_policy(path)

    def test_an_undeclared_category_is_rejected(self) -> None:
        policy = minimal_policy()
        policy["denylist"][0]["category"] = "spyware"
        with policy_file(policy) as path:
            with self.assertRaisesRegex(checker.PolicyError, "not declared"):
                checker.load_policy(path)

    def test_a_group_rule_outside_maven_is_rejected(self) -> None:
        policy = minimal_policy()
        policy["denylist"][1]["match"] = "group"
        with policy_file(policy) as path:
            with self.assertRaisesRegex(checker.PolicyError, "only defined for maven"):
                checker.load_policy(path)

    def test_an_exact_maven_rule_needs_a_full_coordinate(self) -> None:
        policy = minimal_policy()
        policy["denylist"][4]["match"] = "exact"
        with policy_file(policy) as path:
            with self.assertRaisesRegex(checker.PolicyError, "group:artifact"):
                checker.load_policy(path)

    def test_a_future_policy_version_is_refused_rather_than_guessed_at(self) -> None:
        with policy_file(minimal_policy(version=2)) as path:
            with self.assertRaisesRegex(checker.PolicyError, "unsupported policy"):
                checker.load_policy(path)

    def test_the_shipped_policy_has_no_unexplained_exceptions(self) -> None:
        # Not a rule the checker enforces — an exception is allowed to exist.
        # It is the state PRIVACY.md and docs/tracker-dependency-audit.md
        # describe, so a PR that adds one has to update them too, and this test
        # is where that gets noticed.
        policy = checker.load_policy(POLICY_PATH)
        self.assertEqual(
            policy.exceptions,
            (),
            "The shipped policy grants no exceptions. If that changes, update "
            "PRIVACY.md and docs/tracker-dependency-audit.md in the same PR.",
        )


