class ParserTest(unittest.TestCase):
    def test_the_lockfile_sdk_block_is_not_read_as_a_package(self) -> None:
        names = {o.identifier for o in checker.parse_pubspec_lock(CLEAN_LOCK)}
        self.assertEqual(names, {"audio_service", "flutter"})

    def test_the_lockfile_kind_is_kept(self) -> None:
        kinds = {o.identifier: o.detail for o in checker.parse_pubspec_lock(CLEAN_LOCK)}
        self.assertEqual(kinds["audio_service"], "direct main")

    def test_a_pub_version_with_a_dash_still_yields_the_package_name(self) -> None:
        sources = json.dumps(
            [
                {
                    "type": "archive",
                    "dest": ".pub-cache/hosted/pub.dev/just_audio-0.9.42-beta.1",
                },
                {
                    "type": "inline",
                    "dest": ".pub-cache/hosted-hashes/pub.dev",
                },
            ]
        )
        found = checker.parse_flatpak_pub_sources(sources, "pubspec.json")
        self.assertEqual([o.identifier for o in found], ["just_audio"])

    def test_gradle_comments_are_stripped_without_eating_urls(self) -> None:
        stripped, literals = checker.strip_gradle_comments(
            'maven { url "https://pub.dev" } // a comment\n'
        )
        self.assertIn("https://pub.dev", stripped)
        self.assertNotIn("a comment", stripped)
        self.assertEqual(literals, ["https://pub.dev"])

    def test_a_triple_quoted_string_does_not_swallow_the_rest_of_the_file(self) -> None:
        gradle = "def notes = '''nothing to see'''\nplugins { id \"kotlin-android\" }\n"
        found = checker.parse_gradle(gradle, "build.gradle")
        self.assertEqual(
            [o.identifier for o in found if o.ecosystem == "gradle-plugin"],
            ["kotlin-android"],
        )

    def test_apply_plugin_is_read_as_a_plugin_id(self) -> None:
        found = checker.parse_gradle(
            "apply plugin: 'com.google.gms.google-services'\n", "build.gradle"
        )
        self.assertIn("com.google.gms.google-services", [o.identifier for o in found])

    def test_a_coordinate_without_a_version_is_still_a_coordinate(self) -> None:
        found = checker.parse_gradle(
            'implementation "io.sentry:sentry-android"\n', "build.gradle"
        )
        self.assertEqual(
            [o.identifier for o in found if o.ecosystem == "maven"],
            ["io.sentry:sentry-android"],
        )


