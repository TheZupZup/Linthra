class NoFalsePositivesTest(unittest.TestCase):
    """A check that fires on innocent names gets switched off, and then it
    protects nothing. These are the names that a substring rule would flag."""

    def test_an_audio_package_that_reads_like_an_analytics_vendor_passes(self) -> None:
        # "amplitude" is an ordinary audio word. A music player will have
        # packages with it in the name; `amplitude_flutter` is the SDK.
        lock = CLEAN_LOCK.replace(
            "  audio_service:",
            "  amplitude_visualizer:\n    dependency: transitive\n"
            '    source: hosted\n    version: "1.2.0"\n  audio_service:',
        )
        with tree(lock=lock) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 0, output)

    def test_a_package_that_merely_starts_the_same_passes(self) -> None:
        lock = CLEAN_LOCK.replace(
            "  audio_service:",
            "  firebase_analytics_stub_for_tests:\n    dependency: transitive\n"
            '    source: hosted\n    version: "1.0.0"\n  audio_service:',
        )
        with tree(lock=lock) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 0, output)

    def test_a_maven_group_rule_does_not_swallow_a_longer_group(self) -> None:
        gradle = CLEAN_GRADLE + """
dependencies {
    implementation "com.google.firebaseui:firebase-ui-auth:8.0.2"
    implementation "com.google.android.material:material:1.11.0"
}
"""
        with tree(gradle=gradle) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 0, output)

    def test_a_vendor_named_in_a_comment_is_not_a_dependency(self) -> None:
        gradle = """\
// We deliberately do not use com.google.firebase:firebase-analytics here;
/* nor com.google.gms.google-services, see docs/fdroid-readiness.md */
plugins {
    id "com.android.application"
}
"""
        with tree(gradle=gradle) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 0, output)

    def test_a_url_in_a_gradle_file_is_not_a_maven_coordinate(self) -> None:
        gradle = CLEAN_GRADLE + """
repositories {
    maven { url "https://storage.googleapis.com/download.flutter.io" }
}
"""
        with tree(gradle=gradle) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 0, output)

    def test_applicationid_is_not_read_as_a_plugin_id(self) -> None:
        with tree() as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy, "--json")
        self.assertEqual(code, 0, output)
        report = json.loads(output)
        gradle = next(
            item
            for item in report["inspected"]
            if item["source"] == "android/app/build.gradle"
        )
        self.assertEqual(gradle["identifiers"], {"gradle plugin ids": 2})


