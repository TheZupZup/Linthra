#!/usr/bin/env python3
"""Unit tests for scripts/check_tracker_dependencies.py (#504).

    python3 test/tooling/check_tracker_dependencies_test.py

The check's whole value is that people keep it switched on, which means two
failure modes matter equally: missing a real tracking SDK, and crying wolf over
a package that merely reads like one. Both are tested here, along with the
policy loader — the reviewed data is the claim the check makes, so a file it
would silently half-read is a failure of its own.

The real repository is read, never written. Everything else is built in
temporary directories, and nothing here touches the network.
"""

