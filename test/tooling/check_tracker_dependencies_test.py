def _clean_pub_sources(*names: str) -> str:
    return json.dumps(
        [
            {
                "type": "archive",
                "url": f"https://pub.dev/api/archives/{name}-1.0.0.tar.gz",
                "dest": f".pub-cache/hosted/pub.dev/{name}-1.0.0",
            }
            for name in names
        ]
    )


@contextlib.contextmanager
def tree(
    *,
    lock: str = CLEAN_LOCK,
    gradle: str = CLEAN_GRADLE,
    cmake: str = CLEAN_CMAKE,
    cargo: str = CLEAN_CARGO,
    pub_sources: str | None = None,
):
    """A minimal repository with one of every file the check insists on."""
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        (root / "flatpak" / "generated" / "sources").mkdir(parents=True)
        (root / "linux" / "flutter").mkdir(parents=True)
        (root / "android" / "app").mkdir(parents=True)
        (root / "native" / "linthra_core").mkdir(parents=True)

        (root / "pubspec.lock").write_text(lock, encoding="utf-8")
        (root / "flatpak" / "generated" / "sources" / "pubspec.json").write_text(
            pub_sources if pub_sources is not None else _clean_pub_sources("audio_service"),
            encoding="utf-8",
        )
        (root / "linux" / "flutter" / "generated_plugins.cmake").write_text(
            cmake, encoding="utf-8"
        )
        (root / "android" / "app" / "build.gradle").write_text(gradle, encoding="utf-8")
        (root / "native" / "linthra_core" / "Cargo.lock").write_text(
            cargo, encoding="utf-8"
        )
        yield root


@contextlib.contextmanager
def policy_file(policy: dict):
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "tracker_policy.json"
        path.write_text(json.dumps(policy, indent=2), encoding="utf-8")
        yield path


def run(root: Path, policy: Path, *extra: str) -> tuple[int, str]:
    """Run the check the way CI does and capture what a reviewer would read."""
    out = io.StringIO()
    err = io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = checker.main(["--root", str(root), "--policy", str(policy), *extra])
    return code, out.getvalue() + err.getvalue()


def minimal_policy(**changes) -> dict:
    return {**json.loads(json.dumps(MINIMAL_POLICY)), **changes}


