class DisallowedDependencyTest(unittest.TestCase):
    def test_a_locked_analytics_package_fails(self) -> None:
        lock = CLEAN_LOCK.replace(
            "  audio_service:", "  firebase_analytics:\n    dependency: transitive\n"
            "    source: hosted\n    version: \"11.0.0\"\n  audio_service:"
        )
        with tree(lock=lock) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 1, output)
        self.assertIn("FAIL", output)

    def test_the_output_names_the_dependency_its_file_and_the_reason(self) -> None:
        sources = _clean_pub_sources("audio_service", "firebase_analytics")
        with tree(pub_sources=sources) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 1, output)
        self.assertIn("firebase_analytics", output)
        self.assertIn("flatpak/generated/sources/pubspec.json", output)
        self.assertIn("Reports app events to Google.", output)
        self.assertIn("Google (Firebase)", output)
        self.assertIn("Analytics SDKs", output)

    def test_a_finding_says_how_the_package_entered_the_graph(self) -> None:
        lock = CLEAN_LOCK.replace(
            "  audio_service:",
            '  amplitude_flutter:\n    dependency: "direct main"\n'
            '    source: hosted\n    version: "4.0.0"\n  audio_service:',
        )
        with tree(lock=lock) as root, policy_file(MINIMAL_POLICY) as policy:
            _, output = run(root, policy)
        self.assertIn("pubspec.lock (direct main)", output)

    def test_a_gradle_dependency_fails(self) -> None:
        gradle = CLEAN_GRADLE + """
dependencies {
    implementation "com.google.firebase:firebase-analytics:21.5.0"
}
"""
        with tree(gradle=gradle) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 1, output)
        self.assertIn("com.google.firebase:firebase-analytics", output)
        self.assertIn('maven group policy entry "com.google.firebase"', output)

    def test_a_gradle_plugin_fails(self) -> None:
        gradle = CLEAN_GRADLE.replace(
            '    id "kotlin-android"',
            '    id "kotlin-android"\n    id "com.google.gms.google-services"',
        )
        with tree(gradle=gradle) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 1, output)
        self.assertIn("com.google.gms.google-services", output)

    def test_the_kotlin_dsl_spelling_fails_too(self) -> None:
        with tree() as root, policy_file(MINIMAL_POLICY) as policy:
            (root / "android" / "app" / "build.gradle.kts").write_text(
                'dependencies {\n'
                '    implementation("com.google.firebase:firebase-crashlytics:19.0.0")\n'
                "}\n",
                encoding="utf-8",
            )
            code, output = run(root, policy)
        self.assertEqual(code, 1, output)
        self.assertIn("com.google.firebase:firebase-crashlytics", output)

    def test_a_crash_reporting_crate_fails(self) -> None:
        cargo = CLEAN_CARGO + '\n[[package]]\nname = "sentry"\nversion = "0.34.0"\n'
        with tree(cargo=cargo) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 1, output)
        self.assertIn("sentry", output)
        self.assertIn("Automatic third-party crash reporting", output)

    def test_a_plugin_linked_into_the_linux_binary_fails(self) -> None:
        cmake = CLEAN_CMAKE.replace(
            "  url_launcher_linux", "  url_launcher_linux\n  firebase_analytics"
        )
        with tree(cmake=cmake) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy)
        self.assertEqual(code, 1, output)
        self.assertIn("linux/flutter/generated_plugins.cmake", output)

    def test_one_dependency_in_two_files_is_reported_once_with_both(self) -> None:
        lock = CLEAN_LOCK.replace(
            "  audio_service:",
            '  firebase_analytics:\n    dependency: "direct main"\n'
            '    source: hosted\n    version: "11.0.0"\n  audio_service:',
        )
        sources = _clean_pub_sources("audio_service", "firebase_analytics")
        with tree(lock=lock, pub_sources=sources) as root:
            with policy_file(MINIMAL_POLICY) as policy:
                code, output = run(root, policy, "--json")
        self.assertEqual(code, 1, output)
        report = json.loads(output)
        self.assertEqual(len(report["findings"]), 1)
        self.assertEqual(
            [entry["source"] for entry in report["findings"][0]["found_in"]],
            ["flatpak/generated/sources/pubspec.json", "pubspec.lock"],
        )

    def test_a_group_rule_reports_each_coordinate_separately(self) -> None:
        # One policy line can match several artifacts. Collapsing them would
        # print one name and silently drop the rest, which is the one thing the
        # output must never do.
        gradle = CLEAN_GRADLE + """
dependencies {
    implementation "com.google.firebase:firebase-analytics:21.5.0"
    implementation "com.google.firebase:firebase-crashlytics:19.0.0"
}
"""
        with tree(gradle=gradle) as root, policy_file(MINIMAL_POLICY) as policy:
            code, output = run(root, policy, "--json")
        self.assertEqual(code, 1, output)
        report = json.loads(output)
        self.assertEqual(
            [finding["identifier"] for finding in report["findings"]],
            [
                "com.google.firebase:firebase-analytics",
                "com.google.firebase:firebase-crashlytics",
            ],
        )

    def test_the_failure_says_what_to_do_next(self) -> None:
        sources = _clean_pub_sources("firebase_analytics")
        with tree(pub_sources=sources) as root, policy_file(MINIMAL_POLICY) as policy:
            _, output = run(root, policy)
        self.assertIn("needs a human decision", output)
        self.assertIn("docs/tracker-dependency-audit.md", output)
        self.assertIn("exceptions", output)


